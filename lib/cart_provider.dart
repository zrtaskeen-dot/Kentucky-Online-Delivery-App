import 'package:flutter/material.dart';
import 'package:cloud_firestore/cloud_firestore.dart';

class CartItem {
  final String name;
  final String imageUrl;
  final double price;
  final String category;
  int quantity;

  CartItem({
    required this.name,
    required this.imageUrl,
    required this.price,
    required this.category,
    this.quantity = 1,
  });
}

class CartProvider with ChangeNotifier {
  // Har branch ka apna cart: branchId -> us branch ke items.
  // Cart system aik hi hai, bas items us branch ke hisaab se yaad rehte hain
  // jahan se add kiye gaye.
  final Map<String, List<CartItem>> _branchItems = {};
  String _selectedBranchId = ''; // Active branch id state
  double _deliveryCharge = 50; // Fallback until the branch's own value loads

  // Sirf ACTIVE branch ke items (baqi sab getters isi par chalte hain).
  List<CartItem> get items =>
      _branchItems.putIfAbsent(_selectedBranchId, () => <CartItem>[]);

  // Getter: read the active branch id from any screen.
  String get selectedBranchId => _selectedBranchId;

  // Setter: call this when the branch is changed on HomeScreen.
  void setBranchId(String branchId) {
    // Branch select hone se pehle jo items add hue (key ''), wo pehli
    // asli branch ke cart mein shamil kar do, warna gum ho jate.
    if (_selectedBranchId.isEmpty && branchId.isNotEmpty) {
      final orphans = _branchItems.remove('');
      if (orphans != null && orphans.isNotEmpty) {
        final target = _branchItems.putIfAbsent(branchId, () => <CartItem>[]);
        for (final item in orphans) {
          final i = target.indexWhere((e) => e.name == item.name);
          if (i >= 0) {
            target[i].quantity += item.quantity;
          } else {
            target.add(item);
          }
        }
      }
    }
    _selectedBranchId = branchId;
    notifyListeners(); // Notifies the whole app of the branch change.
  }

  // The selected branch's delivery charge, from restaurant_info.
  double get deliveryCharge => _deliveryCharge;

  void setDeliveryCharge(double charge) {
    _deliveryCharge = charge;
    notifyListeners();
  }

  // Cart badge count: ACTIVE branch ke items ki quantity ka total.
  int get itemCount => items.fold(0, (sum, item) => sum + item.quantity);

  double get totalPrice {
    return items.fold(0.0, (sum, item) => sum + (item.price * item.quantity));
  }

  void addItem(CartItem item) {
    final list = items;
    final index = list.indexWhere((element) => element.name == item.name);
    if (index >= 0) {
      list[index].quantity += item.quantity;
    } else {
      list.add(item);
    }
    notifyListeners();
  }

  void removeItem(String name) {
    items.removeWhere((item) => item.name == name);
    notifyListeners();
  }

  void clearCart() {
    items.clear();
    notifyListeners();
  }

  // Call this right AFTER the order has been saved in the `orders`
  // collection. Deletes the ordered items (this user's cart documents of
  // the active branch, plus old ones without a branchId — the same filter
  // the cart screen uses) from Firestore `carts`, then empties the
  // in-memory list too. Other branches' carts are left untouched.
  Future<void> clearCartInFirestore(String userId) async {
    try {
      await CartService.clearBranch(userId, _selectedBranchId);
    } catch (e) {
      // The order is already placed — never fail it because of cart cleanup.
      debugPrint('Could not clear cart in Firestore: $e');
    }
    clearCart();
  }
}

// ─────────────────────────────────────────────────────────────────────
// CART STORAGE (Firestore `carts` collection) — one cart document per
// branch (document id is auto-generated by Firestore; the customer's id
// is stored in the `userId` field). Kept in this file on purpose.
// ─────────────────────────────────────────────────────────────────────

/// One line of the cart (one item) and where it is stored.
///
/// New style : one cart document PER BRANCH (auto-generated document id,
///             with `userId` and `branchId` fields), holding all of that
///             branch's items in its `items` list  ->  [lineId] is set.
/// Old style : one document per item (random id)  ->  [lineId] is null.
///             Kept readable so nothing already in a cart disappears.
class CartLine {
  final String docId;
  final String? lineId;
  final Map<String, dynamic> data;

  const CartLine({
    required this.docId,
    required this.lineId,
    required this.data,
  });
}

class CartService {
  CartService._();

  static CollectionReference<Map<String, dynamic>> get _carts =>
      FirebaseFirestore.instance.collection('carts');

  // ── ADD ─────────────────────────────────────────────────────────────
  /// Adds [item] to this customer's cart document of the item's branch
  /// (read from item['branchId']).
  ///  - If that branch already has a cart document for this customer, the item
  ///    is appended to its `items` list.
  ///  - Otherwise a NEW document is created. Its id is generated by Firestore;
  ///    the customer is identified by the `userId` field inside it.
  /// Another branch therefore always gets its own, separate document.
  static Future<void> addItem(String userId, Map<String, dynamic> item) async {
    final branchId = (item['branchId'] ?? '').toString();
    // The branch is stored ONCE, on the cart document itself (`branchId`),
    // so it is removed from the item to avoid repeating it in every item.
    final line = <String, dynamic>{
      ...item,
      'lineId': DateTime.now().microsecondsSinceEpoch.toString(),
      'addedAt':
          Timestamp.now(), // serverTimestamp() is not allowed inside lists
    }..remove('branchId');

    // Find this customer's existing cart document for this branch.
    // (Old one-item-per-document carts have no `items` list, so they never match.)
    final mine = await _carts.where('userId', isEqualTo: userId).get();
    DocumentReference<Map<String, dynamic>>? existing;
    for (final doc in mine.docs) {
      final d = doc.data();
      if (d['items'] is List && (d['branchId'] ?? '').toString() == branchId) {
        existing = doc.reference;
        break;
      }
    }

    if (existing != null) {
      await existing.update({
        'items': FieldValue.arrayUnion([line]),
        'updatedAt': FieldValue.serverTimestamp(),
      });
    } else {
      await _carts.add({
        'userId': userId,
        if (branchId.isNotEmpty) 'branchId': branchId,
        'items': [line],
        'updatedAt': FieldValue.serverTimestamp(),
      });
    }
  }

  // ── READ ────────────────────────────────────────────────────────────
  /// Turns the documents returned by the `carts` query (where userId == uid)
  /// into a flat list of cart lines, oldest first.
  static List<CartLine> linesFromDocs(Iterable<QueryDocumentSnapshot> docs) {
    final lines = <CartLine>[];
    for (final doc in docs) {
      final data = (doc.data() as Map<String, dynamic>?) ?? {};
      final items = data['items'];
      if (items is List) {
        final docBranch = (data['branchId'] ?? '').toString();
        for (final e in items) {
          if (e is Map) {
            final m = Map<String, dynamic>.from(e);
            // line.data['branchId'] always works: it comes from the cart document.
            if (docBranch.isNotEmpty) m['branchId'] = docBranch;
            lines.add(
              CartLine(docId: doc.id, lineId: m['lineId']?.toString(), data: m),
            );
          }
        }
      } else {
        lines.add(CartLine(docId: doc.id, lineId: null, data: data));
      }
    }
    int stamp(CartLine l) {
      final t = l.data['addedAt'];
      return t is Timestamp ? t.millisecondsSinceEpoch : 0;
    }

    lines.sort((a, b) => stamp(a).compareTo(stamp(b)));
    return lines;
  }

  // ── QUANTITY / REMOVE ───────────────────────────────────────────────
  /// Sets the quantity of one line. A quantity of 0 or less removes it.
  static Future<void> setQuantity(CartLine line, int newQty) async {
    final ref = _carts.doc(line.docId);

    // old style: the line is its own document
    if (line.lineId == null) {
      if (newQty <= 0) {
        await ref.delete();
      } else {
        await ref.update({'quantity': newQty});
      }
      return;
    }

    // new style: change one entry inside the `items` list
    await FirebaseFirestore.instance.runTransaction((tx) async {
      final snap = await tx.get(ref);
      if (!snap.exists) return;
      final items = _itemsOf(snap.data());
      final i = items.indexWhere((e) => e['lineId']?.toString() == line.lineId);
      if (i < 0) return;
      if (newQty <= 0) {
        items.removeAt(i);
      } else {
        items[i]['quantity'] = newQty;
      }
      if (items.isEmpty) {
        tx.delete(ref);
      } else {
        tx.update(ref, {
          'items': items,
          'updatedAt': FieldValue.serverTimestamp(),
        });
      }
    });
  }

  static Future<void> removeLine(CartLine line) => setQuantity(line, 0);

  // ── SALES COUNT (for the "Best Selling" tag) ─────────────────────────
  /// Adds the ordered quantities to each menu item's `soldCount`. Call it right
  /// after the order is saved and BEFORE [clearBranch] (it reads the cart).
  /// Never throws: a problem here must never affect the order itself.
  static Future<void> recordSales(String userId, String activeBranchId) async {
    try {
      final snap = await _carts.where('userId', isEqualTo: userId).get();
      final perItem = <String, int>{};
      for (final line in linesFromDocs(snap.docs)) {
        final b = (line.data['branchId'] ?? '').toString();
        if (b.isNotEmpty && b != activeBranchId) continue;
        final menuItemId = (line.data['menuItemId'] ?? '').toString();
        if (menuItemId.isEmpty) continue; // e.g. smart combos
        final qty = int.tryParse('${line.data['quantity']}') ?? 1;
        perItem[menuItemId] = (perItem[menuItemId] ?? 0) + qty;
      }
      for (final e in perItem.entries) {
        try {
          await FirebaseFirestore.instance.collection('menu').doc(e.key).update(
            {'soldCount': FieldValue.increment(e.value)},
          );
        } catch (err) {
          debugPrint('Could not update soldCount for ${e.key}: $err');
        }
      }
    } catch (err) {
      debugPrint('recordSales failed: $err');
    }
  }

  // ── CLEAR (after the order is placed) ───────────────────────────────
  /// Removes this customer's ordered items from the cart: the cart document of
  /// [activeBranchId] (plus old items without a branch). Other branches'
  /// cart documents stay untouched. When nothing is left in a document it is
  /// deleted, so the next add starts a fresh cart for that branch.
  static Future<void> clearBranch(String userId, String activeBranchId) async {
    final snap = await _carts.where('userId', isEqualTo: userId).get();
    if (snap.docs.isEmpty) return;

    bool belongs(Map<String, dynamic> m) {
      final b = (m['branchId'] ?? '').toString();
      return b.isEmpty || b == activeBranchId;
    }

    final batch = FirebaseFirestore.instance.batch();
    for (final doc in snap.docs) {
      final data = doc.data();
      final items = data['items'];
      if (items is List) {
        final docBranch = (data['branchId'] ?? '').toString();
        if (docBranch.isNotEmpty) {
          // Cart document of ONE branch: all its items belong to that branch.
          if (docBranch == activeBranchId) batch.delete(doc.reference);
          continue;
        }
        // Older mixed-branch cart document: decide item by item.
        final keep = _itemsOf(data).where((m) => !belongs(m)).toList();
        if (keep.isEmpty) {
          batch.delete(doc.reference);
        } else {
          batch.update(doc.reference, {
            'items': keep,
            'updatedAt': FieldValue.serverTimestamp(),
          });
        }
      } else if (belongs(data)) {
        batch.delete(doc.reference); // old style one-item document
      }
    }
    await batch.commit();
  }

  static List<Map<String, dynamic>> _itemsOf(Map<String, dynamic>? data) {
    final raw = data?['items'];
    if (raw is! List) return <Map<String, dynamic>>[];
    return raw
        .whereType<Map>()
        .map((e) => Map<String, dynamic>.from(e))
        .toList();
  }
}
